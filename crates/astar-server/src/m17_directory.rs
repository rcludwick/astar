    #[test]
    fn live_from_keeps_the_running_directory_and_rereads_only_the_table() {
        let cfg = crate::config::M17Cfg {
            enabled: false,
            directory: None,
            codec_dirs: vec![],
            reflectors: BTreeMap::from([("m17-xyz".to_string(), "m17.example.net".to_string())]),
        };
        let running = M17Settings {
            enabled: true,
            reflectors: BTreeMap::new(),
            directory: Some(Directory::bundled().expect("the bundled snapshot parses")),
        };

        let live = M17Settings::live_from(&cfg, Some(&running)).expect("a valid section");
        assert!(!live.enabled);
        assert_eq!(
            live.reflectors,
            BTreeMap::from([(
                "M17-XYZ".to_string(),
                ("m17.example.net".to_string(), DEFAULT_M17_PORT)
            )])
        );
        assert_eq!(
            live.directory_generated(),
            Some("2026-09-15"),
            "directory is restart-tier: the running one stays"
        );

        assert!(
            M17Settings::live_from(&cfg, None)
                .expect("a valid section")
                .directory
                .is_none(),
            "a section added at run time has no directory until a restart"
        );
        let named = crate::config::M17Cfg {
            directory: Some(BUNDLED.to_string()),
            ..cfg.clone()
        };
        assert!(
            M17Settings::live_from(&named, None)
                .expect("a valid section")
                .directory
                .is_none(),
            "a directory named on disk is not loaded by a live apply"
        );
        let bad = crate::config::M17Cfg {
            codec_dirs: vec!["lib".to_string()],
            ..cfg.clone()
        };
        assert_eq!(
            M17Settings::live_from(&bad, Some(&running)).unwrap_err(),
            "m17.codec_dirs: \"lib\" is not an absolute path",
            "the same checks as load"
        );
    }
